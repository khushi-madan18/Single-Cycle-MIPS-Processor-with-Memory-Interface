#!/usr/bin/env python3
"""
export_ui_data.py - package the sample programs and the Verilog simulation
traces for the web UI (ui/data/*.js). Run after tools/run_tests.py, which
creates simulation/<name>_trace.txt for every programs/*.asm.

    python3 tools/export_ui_data.py
"""
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from run_tests import parse_trace, CTRL_KEYS  # noqa: E402

ORDER = ["basic_test", "array_sum", "max_search", "factorial"]
TITLES = {"basic_test": "Basic test (all instructions)", "array_sum": "Array sum",
          "max_search": "Maximum search", "factorial": "Factorial (6!)"}


def main():
    out_dir = os.path.join(ROOT, "ui", "data")
    os.makedirs(out_dir, exist_ok=True)
    names = [n for n in ORDER if os.path.exists(os.path.join(ROOT, "programs", n + ".asm"))]
    names += sorted(os.path.splitext(os.path.basename(p))[0] for p in glob.glob(os.path.join(ROOT, "programs", "*.asm"))
                    if os.path.splitext(os.path.basename(p))[0] not in names)
    programs, traces = [], {}
    for n in names:
        with open(os.path.join(ROOT, "programs", n + ".asm")) as f:
            programs.append({"id": n, "title": TITLES.get(n, n), "source": f.read()})
        tpath = os.path.join("simulation", n + "_trace.txt")
        if os.path.exists(os.path.join(ROOT, tpath)):
            rows = parse_trace(tpath)
            # compact: [pc, instr, ctrl bits, alu_op, alu_ctrl, alu_result, zero, write_reg, write_back, mem_we, next_pc]
            traces[n] = [[r["pc"], r["instr"], "".join(str(r[k]) for k in CTRL_KEYS), r["alu_op"], r["alu_ctrl"],
                          r["alu_result"], r["zero"], r["write_reg"], r["write_back"], r["mem_write_en"], r["next_pc"]]
                         for r in rows]
    hdr = "// Generated by tools/export_ui_data.py - do not edit by hand.\n"
    with open(os.path.join(out_dir, "programs.js"), "w") as f:
        f.write(hdr + "window.SAMPLE_PROGRAMS = " + json.dumps(programs, indent=1) + ";\n")
    with open(os.path.join(out_dir, "rtl_traces.js"), "w") as f:
        f.write(hdr + "// Per-cycle signals recorded from the Verilog simulation (testbench/tb_program.v, Icarus Verilog).\n")
        f.write("window.RTL_TRACES = " + json.dumps(traces, separators=(",", ":")) + ";\n")
    print("wrote ui/data/programs.js (%d programs) and ui/data/rtl_traces.js (%d traces)" % (len(programs), len(traces)))


if __name__ == "__main__":
    main()
